#!/usr/bin/env node
/**
 * Generate src/reference/cw-db-schema.ts — the table catalog cw_db_find_table
 * searches.
 *
 * Scope is deliberately narrow: only the objects named in the hand-written
 * ENRICH map in scripts/db-enrich.mjs are emitted. ConnectWise Manage has ~1,300 tables, most of them noise,
 * and a full dump would publish the shape of a specific customer's instance in
 * a public repository. The catalog's job is discovery and steering, not
 * reference — exact column lists come from a live INFORMATION_SCHEMA query,
 * which is always current for the instance actually being queried.
 *
 * Usage:
 *   node scripts/gen-db-schema.mjs                     # annotations only
 *   node scripts/gen-db-schema.mjs .claude/cw-db-schema.json
 *
 * With a dump (produced by scripts/dump-db-schema.sql, kept under the gitignored
 * .claude/), primary keys and key-column types are taken from the real schema
 * instead of the hand annotations, and any ENRICH entry naming a table or column
 * that does not exist is reported. Row counts, custom/UDF tables, and the source
 * host/database/login are never emitted.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { CONVENTIONS, ENRICH } from "./db-enrich.mjs";

const OUT = "src/reference/cw-db-schema.ts";
const KEY_COLUMN_CAP = 16;

/** Columns that must never be echoed into a public catalog. */
const SENSITIVE = /password|passwd|hash|salt|token|secret|private.?key|api.?key|credential|ssn|card/i;
/** Custom fields and per-MSP additions are instance-specific — never emitted. */
const INSTANCE_SPECIFIC = /^(UDF_|Custom_|z_)|_Custom$|_UDF$/i;

function loadDump(path) {
  if (!path) return undefined;
  const parsed = JSON.parse(readFileSync(path, "utf8"));
  const columns = new Map();
  for (const column of parsed.columns ?? []) {
    const list = columns.get(column.table) ?? [];
    list.push(column);
    columns.set(column.table, list);
  }
  const pks = new Map();
  for (const pk of parsed.primaryKeys ?? []) {
    if (!pks.has(pk.table)) pks.set(pk.table, pk.column);
  }
  return { tables: new Set((parsed.tables ?? []).map((t) => t.name)), columns, pks };
}

/** "Name type" for the first KEY_COLUMN_CAP interesting columns of a table. */
function columnsFromDump(dump, table, hinted) {
  const all = dump.columns.get(table);
  if (!all) return undefined;
  const wanted = new Set(hinted.map((name) => name.toLowerCase()));
  const picked = all
    .filter((column) => !SENSITIVE.test(column.column) && !INSTANCE_SPECIFIC.test(column.column))
    .filter((column) => wanted.size === 0 || wanted.has(column.column.toLowerCase()))
    .sort((a, b) => a.ord - b.ord)
    .slice(0, KEY_COLUMN_CAP);
  if (picked.length === 0) return undefined;
  return picked.map((column) => `${column.column} ${column.type}`).join(", ");
}

function main() {
  const dumpPath = process.argv[2];
  const dump = loadDump(dumpPath);
  const problems = [];

  const entries = Object.entries(ENRICH)
    .filter(([name]) => {
      if (INSTANCE_SPECIFIC.test(name)) return false;
      if (dump && !dump.tables.has(name)) {
        problems.push(`table ${name} is in ENRICH but not in the dump`);
        return false;
      }
      return true;
    })
    .map(([name, entry]) => {
      const hinted = (entry.keyColumns ?? "")
        .split(",")
        .map((part) => part.trim().split(/\s+/)[0])
        .filter(Boolean);
      const fromDump = dump ? columnsFromDump(dump, name, hinted) : undefined;
      if (dump && !fromDump) problems.push(`no usable columns found for ${name}`);
      return {
        schema: "dbo",
        name,
        purpose: entry.purpose,
        ...(entry.keywords ? { keywords: entry.keywords } : {}),
        ...(dump?.pks.get(name) || entry.pk ? { pk: dump?.pks.get(name) ?? entry.pk } : {}),
        ...(fromDump || entry.keyColumns ? { keyColumns: fromDump ?? entry.keyColumns } : {}),
        ...(entry.joins ? { joins: entry.joins } : {}),
        ...(entry.coveredBy ? { coveredBy: entry.coveredBy } : {}),
        ...(entry.size ? { size: entry.size } : {}),
        ...(entry.notes ? { notes: entry.notes } : {}),
      };
    })
    .sort((a, b) => a.name.localeCompare(b.name));

  const provenance = dump
    ? "Key columns and primary keys were refreshed from a redacted INFORMATION_SCHEMA dump."
    : "Object and column names were read off production reporting queries; run the generator with a dump to verify them against a live schema.";

  const file = `/**
 * ConnectWise Manage database catalog — GENERATED by scripts/gen-db-schema.mjs.
 * DO NOT EDIT BY HAND: change the ENRICH map in the generator and re-run it.
 *
 * A curated core, not an inventory: only tables worth steering a query toward
 * are listed, and only their key columns. For a table's exact columns, query
 * INFORMATION_SCHEMA through cw_db_query — that is always current for the
 * instance being queried, and costs nothing here.
 *
 * ${provenance}
 * No row counts, no custom/UDF tables, and no credential columns are included.
 */

export interface TableDoc {
  /** Almost always "dbo"; "(conventions)" for the schema-conventions entry. */
  schema: string;
  /** As SQL Server spells it, e.g. "SR_Service". */
  name: string;
  purpose: string;
  /** Extra search terms for the entry points — what people call this thing. */
  keywords?: string;
  /** Primary key column. */
  pk?: string;
  /** Key columns with types — not the full column list. */
  keyColumns?: string;
  /** How this table joins to the others. */
  joins?: string;
  /** Curated MCP tool(s) that answer this without SQL. */
  coveredBy?: string;
  /** Rough magnitude, to steer TOP and date bounds. */
  size?: string;
  notes?: string;
}

export const CW_DB_TABLES: TableDoc[] = ${JSON.stringify([CONVENTIONS, ...entries], null, 2)};
`;

  writeFileSync(OUT, file);
  console.log(`${OUT}: ${entries.length + 1} entries${dump ? " (dump-checked)" : ""}`);
  for (const problem of problems) console.warn(`  ! ${problem}`);
}

main();
